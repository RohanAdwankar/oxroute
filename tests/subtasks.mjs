import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const agent = { id: 'subtask-fixture', name: 'Release planning', status: 'complete', backend: 'codex', model: 'fixture', updatedAt: 1 };
const make = (id, text, parentTaskId = '', status = 'incomplete') => ({ id, text, parentTaskId, status, agentId: agent.id, blockedByTaskId: '', images: [], createdAt: 1, updatedAt: 1 });
let tasks = [make('plan', 'Prepare release'), make('archive', 'Earlier work', '', 'complete'), make('artifact', 'Inspect artifact', 'plan'), make('metadata', 'Validate metadata', 'artifact'), make('docs', 'Check guide', 'plan', 'done')];
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1300, height: 900 } });
  await page.addInitScript(() => localStorage.setItem('oxroute.tasks', 'true'));
  await page.route('**/api/state', r => r.fulfill({ json: { mode: 'ask', agents: [agent], archived: [], messages: {}, tasks, taskNotes: [], inbox: [], paneLinks: {}, tags: {}, boards: [], sources: [], models: [], backends: [] } }));
  await page.route('**/api/events', r => r.fulfill({ contentType: 'text/event-stream', body: ': fixture\n\n' }));
  await page.route('**/api/terminals', r => r.fulfill({ json: [] }));
  await page.route('**/api/agents/*', r => r.fulfill({ json: { agent, timeline: [], delivery: 'start' } }));
  const writes = [];
  await page.route('**/api/tasks', r => {
    assert.equal(r.request().method(), 'POST');
    const body = r.request().postDataJSON(); writes.push(body);
    const task = make('new-child', body.text, body.parentTaskId); tasks.push(task);
    return r.fulfill({ json: task });
  });
  await page.route('**/api/tasks/*', r => {
    const id = r.request().url().split('/').pop();
    const body = r.request().postDataJSON(); writes.push(body);
    tasks = tasks.map(task => task.id === id ? { ...task, ...body } : task);
    return r.fulfill({ json: tasks.find(task => task.id === id) });
  });
  await page.goto(`${process.env.TEST_URL ?? 'http://127.0.0.1:3942'}/?agent=${agent.id}`);
  const row = text => page.locator('[data-task-row]').filter({ has: page.locator('[data-task-open]', { hasText: text }) });
  await row('Validate metadata').waitFor();
  assert.deepEqual(await page.locator('[data-task-open]').allTextContents(), ['Prepare release', 'Inspect artifact', 'Validate metadata', 'Check guide']);
  const padding = async text => row(text).evaluate(el => parseFloat(getComputedStyle(el).paddingLeft));
  assert.ok(await padding('Validate metadata') > await padding('Inspect artifact'));
  assert.ok(await padding('Inspect artifact') > await padding('Prepare release'));
  await row('Inspect artifact').click({ button: 'right' });
  const parent = page.getByRole('combobox', { name: 'Parent task', exact: true });
  assert.deepEqual(await parent.locator('option').evaluateAll(options => options.map(o => o.value)), ['', 'plan', 'archive', 'docs']);
  await parent.selectOption('archive');
  await row('Earlier work').waitFor();
  assert.equal(tasks.find(task => task.id === 'artifact').parentTaskId, 'archive');
  assert.equal(tasks.find(task => task.id === 'artifact').status, 'incomplete');
  await page.getByRole('searchbox', { name: 'Search tasks' }).fill('metadata');
  await page.waitForFunction(() => document.querySelectorAll('[data-task-row]').length === 3);
  assert.deepEqual(await page.locator('[data-task-open]').allTextContents(), ['Earlier work', 'Inspect artifact', 'Validate metadata']);
  await page.getByRole('searchbox', { name: 'Search tasks' }).fill('');
  await row('Prepare release').click({ button: 'right' });
  await page.getByRole('button', { name: 'Add subtask', exact: true }).click();
  await page.getByRole('textbox', { name: 'Subtask', exact: true }).fill('Check release notes');
  await page.getByRole('button', { name: 'Add subtask', exact: true }).click();
  await row('Check release notes').waitFor();
  assert.deepEqual(writes.at(-1), { text: 'Check release notes', agentId: agent.id, parentTaskId: 'plan' });
  await row('Check guide').getByRole('button', { name: 'Approve', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('select[aria-label="status for Check guide"]')?.value === 'complete');
  assert.equal(tasks.find(task => task.id === 'plan').status, 'incomplete');
  assert.equal(tasks.find(task => task.id === 'docs').parentTaskId, 'plan');
  await row('Inspect artifact').click({ button: 'right' });
  await parent.selectOption('');
  await page.waitForFunction(() => parseFloat(getComputedStyle([...document.querySelectorAll('[data-task-row]')].find(el => el.textContent.includes('Inspect artifact'))).paddingLeft) === 17);
  assert.ok(await padding('Validate metadata') > await padding('Inspect artifact'));
  if (process.env.SCREENSHOT) await page.screenshot({ path: process.env.SCREENSHOT });
  console.log('Subtasks group across levels, preserve independent approval, retain ancestors in search, create from context menu, move and detach without losing descendants.');
} finally { await browser.close(); }
