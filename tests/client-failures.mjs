import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const url = process.env.TEST_URL ?? 'http://127.0.0.1:3939';
const agent = { id: `missing-${crypto.randomUUID()}`, name: 'Delivery check', status: 'complete', backend: 'codex', model: 'fixture', updatedAt: Date.now()/1000 };
const browser = await chromium.launch();
try {
 const page = await browser.newPage();
 await page.addInitScript(() => { window.SharedWorker = undefined; window.EventSource = class extends EventTarget { close() {} }; });
 await page.route('**/api/state', r => r.fulfill({ json: { mode:'ask', agents:[agent], archived:[], messages:{}, tasks:[], taskNotes:[], inbox:[], paneLinks:{}, tags:{}, boards:[], sources:[], models:[], backends:[] } }));
 await page.route('**/api/agents/*', r => r.fulfill({ json:{ agent, timeline:[], delivery:'start' } }));
 await page.route('**/api/terminals', r => r.fulfill({ json:[] }));
 let reportsAvailable = false;
 await page.route('**/api/client-failures', r => reportsAvailable ? r.continue() : r.abort('connectionrefused'));
 await page.goto(`${url}/?agent=${agent.id}`);
 const composer = page.locator('[data-composer]');
 const text = `Unsent message ${crypto.randomUUID()}`;
 await composer.fill(text);
 await composer.press('Enter');
 await assert.doesNotReject(() => composer.waitFor());
 await page.waitForFunction(() => JSON.parse(localStorage.getItem('oxroute.clientFailures') ?? '[]').some(item => item.path === '/api/say'));
 const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('oxroute.clientFailures')));
 const failure = saved.find(item => item.path === '/api/say');
 assert.equal(failure.agent, agent.id);
 assert.equal(failure.status, 400);
 assert.ok(failure.requestId);
 assert.ok(failure.message.includes('no such agent'));
 assert.ok(!JSON.stringify(saved).includes(text), 'Diagnostics exclude message contents');
 assert.equal(await composer.inputValue(), text, 'Failed send restores the message');
 reportsAvailable = true;
 const report = page.waitForResponse(r => r.url().endsWith('/api/client-failures') && r.request().method() === 'POST' && r.status() === 204);
 await page.reload();
 await report;
 const stored = await (await page.request.get(`${url}/api/client-failures`)).json();
 assert.ok(stored.some(item => item.id === failure.id && item.requestId === failure.requestId), 'Error survives browser reload and reaches the real daemon');
 await page.route('**/api/say', r => r.abort('connectionreset'));
 await composer.fill(`Transport check ${crypto.randomUUID()}`);
 const networkReport = page.waitForResponse(r => r.url().endsWith('/api/client-failures') && r.request().method() === 'POST' && r.status() === 204);
 await composer.press('Enter');
 await networkReport;
 const network = await (await page.request.get(`${url}/api/client-failures`)).json();
 assert.ok(network.some(item => item.agent === agent.id && item.status === 0 && item.requestId !== failure.requestId), 'Transport failures are captured without reaching the send endpoint');
 if (process.env.SCREENSHOT) await page.screenshot({ path:process.env.SCREENSHOT });
 console.log('Failed submissions preserve drafts and automatically deliver diagnostics after reconnection and reload.');
} finally { await browser.close(); }
